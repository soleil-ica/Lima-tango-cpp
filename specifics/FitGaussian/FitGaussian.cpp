        {
            attr.set_value(static_cast<Tango::DevUShort*>(nullptr), 0, 0);
            attr.set_quality(Tango::ATTR_ALARM);
            return;
        }

        const cv::Mat img = yat::any_cast<cv::Mat>(m_fit_task->get_param("ROIImage"));

